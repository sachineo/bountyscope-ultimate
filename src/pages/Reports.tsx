import React, { useEffect, useState, useCallback } from 'react';
import { useApp } from '../context/AppContext';
import { db, newId, nowISO } from '../lib/db';
import { FileText, Download, Copy, Eye, Plus } from 'lucide-react';

const REPORT_TYPES = ['hackerone','bugcrowd','pentest','generic'];

function generateHackerOneReport(finding: any, project: any): string {
  return `# ${finding.title}

## Summary

${finding.summary || 'A security vulnerability was identified during authorized testing of the application.'}

## Asset

${finding.asset || project?.name || 'See details below'}

## Vulnerability Type

${finding.owasp_category || 'See CWE below'}  
**CWE:** ${finding.cwe || 'N/A'}  
**CVSS Score:** ${finding.cvss_score || 'N/A'} ${finding.cvss_vector ? `(${finding.cvss_vector})` : ''}

## Preconditions

${finding.prerequisites || 'Authenticated user session required.' }

## Steps to Reproduce

${finding.steps || '1. [Step 1]\n2. [Step 2]\n3. [Step 3]'}

## Proof of Concept

[Attach screenshots and request/response evidence]

## Observed Result

${finding.observed_result || 'See evidence attached.'}

## Expected Result

${finding.expected_result || 'The application should properly enforce authorization controls.'}

## Impact

**Technical Impact:** ${finding.impact || 'See description.'}

**Business Impact:** ${finding.business_impact || 'Potential for unauthorized access to sensitive data or functionality.'}

## Suggested Severity

**${(finding.severity || 'medium').toUpperCase()}**

## Remediation

${finding.remediation || 'Implement proper server-side authorization checks for all sensitive operations.'}

## Supporting Information

- **Tested by:** Sachin
- **Project:** ${project?.name || 'N/A'}
- **Date:** ${new Date().toLocaleDateString()}
- **Testing conducted on researcher-controlled accounts and data only.**

---
*Report generated by BountyScope Ultimate*
`;
}

